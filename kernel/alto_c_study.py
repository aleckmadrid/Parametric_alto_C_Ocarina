def linfit(x, y):
    n = len(x)
    mx, my = sum(x) / n, sum(y) / n
    b = sum((a - mx) * (c - my) for a, c in zip(x, y)) / sum((a - mx) ** 2 for a in x)
    a = my - b * mx
    ss = sum((c - (a + b * q)) ** 2 for q, c in zip(x, y))
    st = sum((c - my) ** 2 for c in y)
    return a, b, 1 - ss / st


