"""Chamber volume, thickness and size of the ceramic references, from their holes, their outline and their mass.

    python Analizes_ocarinas/Windway_and_body_shape/ceramic_volume_check.py

Two independent routes to the air volume of a body:

  holes     the range identity of docs/03 (Identity 1): sum(G_holes) / (eta_w G_w) is fixed by the scale, so the
            twelve holes give V0 for a chosen lowest note, without the window (the method of Miracle_M.md 6.4).
  outline   outer volume (outline, a thickness / width ratio, elliptical sections) minus the fired clay. The clay
            is mass / density where the mass is known, and surface x wall thickness where it is not.

Spencer        lowest note, mass and an edge-view thickness known -> the two routes bound the air volume.
Songbird Tenor A   size and mass known        -> the two routes give the lowest note the size fits.
Songbird Alto C    lowest note known (A4)     -> the two routes give the body length (the maker states none).

The two Songbird models are taken as one design at two sizes; the holes were measured on the Alto C photos.
Every input is rough: hole diameters are photo rims (+-15 %), thumb holes come from oblique frames, wall thickness
and clay density are assumptions. The output states ranges, not values.
Reads ../Songbird_OoT_12h/measure_output.json and ../Spencer_OoT_12h/measure_output.json. Writes
ceramic_volume_check.md. Standard library and numpy only.
"""
from __future__ import annotations

import json
import math
import pathlib
import sys

import numpy as np

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "kernel"))
import ocarina_kernel as ok  # noqa: E402

MM = 1e-3
MIDI = [69, 71, 72, 74, 76, 77, 79, 81, 83, 84, 86, 88, 89]          # A4 .. F6
C = ok.c_air(27.0)
K = 0.80
EDGE_T_MM = (35.0, 45.0)        # Spencer photo 09_edge_view_in_hands.png, read by eye (see Spencer_OoT_12h.md section 4)
FINGER = ("sub_L", "sub_R", "R_pinky", "R_ring", "R_middle", "R_index", "L_pinky", "L_ring", "L_middle", "L_index")
NOTE = {0: "A4", -1: "G♯4", -2: "G4", -3: "F♯4", -4: "F4", -5: "E4"}


def ratio_needed(walls_mm, shift=0):
    f = [ok.midi_f(m + shift) for m in MIDI]
    holes = [ok.Hole(f"h{i}", t * MM) for i, t in enumerate(walls_mm)]
    des = ok.solve_linear_fingering(f, 1e-3, holes, k=K, c=C)
    return sum(des.G(i) for i in range(12)) / 1e-3


def v0_from_holes(d_mm, walls_mm, shift=0):
    """Capped air volume (cm3) that the twelve holes imply when the all-closed note is A4 shifted by `shift` semitones."""
    sG = sum(ok.conductance(math.pi * (d * MM) ** 2 / 4, t * MM, K) for d, t in zip(d_mm, walls_mm))
    return ok.volume_for(sG / ratio_needed(walls_mm, shift), ok.midi_f(69 + shift), C) * 1e6, sG / MM


def outline(j, scale=1.0):
    """Width profile (mm) and stations (mm) of a measured outline, scaled."""
    w = (np.array(j["player_half_mm"]) + np.array(j["far_half_mm"])) * scale
    s = np.array(j["stations"]) * j["length_mm"] * scale
    return w, s


def outer_volume_cm3(w, s, tw):
    return math.pi / 4.0 * tw * float(np.trapezoid(w * w, s)) / 1000.0


def shell_cm3(w, s, tw, wall):
    """Fired clay of a shell of uniform thickness: surface (perimeter of the elliptical sections, integrated) x wall."""
    a, b = w / 2.0, tw * w / 2.0
    per = math.pi * (3.0 * (a + b) - np.sqrt((3.0 * a + b) * (a + 3.0 * b)))      # Ramanujan
    return float(np.trapezoid(per, s)) * wall / 1000.0


def main():
    md = ["# Ceramic references: volume, thickness and size from holes, outline and mass (generated by ceramic_volume_check.py)", "",
          f"k = {K:.2f}, 27 °C. Hole diameters are the photo rims of the measurement scripts. *Rim − 1 mm* allows for the "
          "rounded, unglazed lip. All numbers are rough; read the ranges.", ""]

    # ---------------- Spencer
    sp = json.load(open(HERE.parent / "Spencer_OoT_12h" / "measure_output.json"))
    d_f = [sp["hole_sizes_mean_mm"][n] for n in FINGER]
    w, s = outline(sp)
    w2 = float(np.trapezoid(w * w, s))
    md += ["## 1. Spencer (165 mm, 330 g, A4–F6): air volume", "",
           "Three inputs, each rough: the twelve holes, the mass, and the thickness read on the edge view "
           f"(photo 09: {EDGE_T_MM[0]:.0f}–{EDGE_T_MM[1]:.0f} mm; the instrument's own scale gives the low end, the width of the fingers the high end).", "",
           "### 1a. From the holes (lowest note A4)", "",
           "Thumb holes 12 ± 2 mm. The chimney is the wall at the hole. The workshop photo of an open half (photo 11) shows about 3 mm at "
           "the thumb holes, which sit at the bottom of pockets; the wall at the finger holes is not known.", "",
           "| Chimney at the holes, mm | V0, cm³: rim − 1 mm, thumbs 10 mm | rim − 1 mm, thumbs 12 | rim, thumbs 12 | rim, thumbs 14 |", "|---|---|---|---|---|"]
    v_all = {}
    for wall in (3.0, 4.0, 5.0, 6.0):
        cells = []
        for off, thumb in ((-1.0, 10.0), (-1.0, 12.0), (0.0, 12.0), (0.0, 14.0)):
            d = [x + off for x in d_f] + [thumb + off, thumb + off]
            cells.append(v0_from_holes(d, [wall] * 12)[0])
        v_all[wall] = cells
        md.append(f"| {wall:.0f} | " + " | ".join(f"{c:.0f}" for c in cells) + " |")
    h_lo, h_hi = min(min(c) for c in v_all.values()), max(max(c) for c in v_all.values())
    md += ["", f"Range {h_lo:.0f}–{h_hi:.0f} cm³. With walls of 5–6 mm (the first pass): "
           f"{min(min(v_all[5.0]), min(v_all[6.0])):.0f}–{max(max(v_all[5.0]), max(v_all[6.0])):.0f} cm³.", "",
           "### 1b. From the outline, the thickness and the mass", "",
           "Outer volume = π/4 × thickness / width × ∫ width² (elliptical sections; a fuller section adds up to 8 %). "
           "Fired clay = (330 g − mouthpiece) / density. Air = outer − clay. The two numbers in a cell are for a mouthpiece of 35 g and of 55 g.", "",
           "| Thickness mm | Thickness / width | Outer cm³ | Air, clay 1.9 g/cm³ | Air, clay 2.1 | Air, clay 2.3 |", "|---|---|---|---|---|---|"]

    def mass_air(T, rho, mp):
        return math.pi / 4.0 * (T / w.max()) * w2 / 1000.0 - (330.0 - mp) / rho

    for T in (35.0, 38.0, 42.0, 45.0, 48.0, 51.0):
        outer = math.pi / 4.0 * (T / w.max()) * w2 / 1000.0
        md.append(f"| {T:.0f} | {T / w.max():.2f} | {outer:.0f} | " + " | ".join(
            f"{mass_air(T, rho, 35.0):.0f}–{mass_air(T, rho, 55.0):.0f}" for rho in (1.9, 2.1, 2.3)) + " |")
    # where the two routes meet
    meet = []
    for T in np.arange(34.0, 56.01, 0.5):
        lo = mass_air(T, 1.9, 35.0)
        hi = mass_air(T, 2.3, 55.0)
        if hi >= h_lo and lo <= h_hi:
            meet.append((T, max(lo, h_lo), min(hi, h_hi)))
    t_meet = meet[0][0]
    at = {T: (a_, b_) for T, a_, b_ in meet}
    top = EDGE_T_MM[1]
    md += ["", "### 1c. Where the routes meet", "",
           f"- The mass route reaches the holes route ({h_lo:.0f}–{h_hi:.0f} cm³) only from a thickness of **{t_meet:.1f} mm** up."
           f" At {top:.0f} mm, the top of what the edge view allows, the two overlap at **{at[top][0]:.0f}–{at[top][1]:.0f} cm³**.",
           f"- A thickness of 35–40 mm with 330 g would leave at most {mass_air(35.0, 2.3, 55.0):.0f} cm³ (35 mm) to {mass_air(40.0, 2.3, 55.0):.0f} cm³ (40 mm) of air: "
           "too little for A4 with these holes. So the body is at the thick end of the edge-view reading, or lighter than 330 g.",
           f"- **Working value: about 70 cm³ of air (65–80), in a body about {top:.0f} mm thick (thickness / width {top / w.max():.2f}).** "
           f"The fired clay is then {(330.0 - 45.0) / 2.3:.0f}–{(330.0 - 45.0) / 1.9:.0f} cm³: about two thirds of the body is clay. "
           "The three inputs only just meet, so this value needs a dense clay (2.1–2.3 g/cm³) and the thick end of the photo reading.",
           "- The first pass read thickness / width 0.8–0.9 (44–56 mm) from the holes and the mass alone. The edge view cuts the top of that range.", ""]

    # ---------------- Songbird: one design, two sizes
    sb = json.load(open(HERE.parent / "Songbird_OoT_12h" / "measure_output.json"))
    L0 = sb["length_mm"]
    frac = [sb["holes"][n]["d_rim_major"] / L0 for n in FINGER]
    thumbs = [sb["thumb_face"]["feats"]["R_thumb"]["size_frac"], sb["thumb_face"]["feats"]["L_thumb"]["size_frac"]]
    ten = sb["tenor_a"]

    # Tenor A
    LT = ten["length_mm"]
    w, s = outline(sb, LT / L0)
    md += ["## 2. Songbird Tenor A (203 mm, just under 1 lb): the lowest note its size fits", "",
           f"Assumption: the Tenor A is the Alto C design scaled by {LT / L0:.3f}. Thickness 57 mm (maker). Width: {w.max():.1f} mm by the "
           f"scaled outline, 76 mm by the maker. Mass 420–450 g, mouthpiece 50 g.", "",
           "| Thickness / width | Clay density g/cm³ | Mass g | Outer volume cm³ | Fired clay cm³ | Air by the outline route cm³ |", "|---|---|---|---|---|---|"]
    airs = []
    for tw in (ten["tw_maker"], ten["tw_with_measured_width"]):
        outer = outer_volume_cm3(w, s, tw)
        for rho in (2.1, 2.4):
            for mass in (420.0, 450.0):
                clay = (mass - 50.0) / rho
                airs.append(outer - clay)
                md.append(f"| {tw:.2f} | {rho:.1f} | {mass:.0f} | {outer:.0f} | {clay:.0f} | {outer - clay:.0f} |")
    md += ["", f"Thumb holes: {thumbs[0] * LT:.1f} and {thumbs[1] * LT:.1f} mm rims, scaled from the Alto C thumb-face frame.", "",
           "| Hole diameters | Wall mm | Σ G mm | V0 if the lowest note is " + " | … ".join(NOTE[sh] for sh in (0, -2, -3, -4, -5)) + " |",
           "|---|---|---|---|---|---|---|---|"]
    for label, off in (("rim", 0.0), ("rim − 1 mm", -1.0)):
        for wall in (5.0, 6.0):
            d = [f * LT + off for f in frac] + [t * LT + off for t in thumbs]
            cells = [v0_from_holes(d, [wall] * 12, sh) for sh in (0, -2, -3, -4, -5)]
            md.append(f"| {label} | {wall:.0f} | {cells[0][1]:.1f} | " + " | ".join(f"{c[0]:.0f}" for c in cells) + " |")
    md += ["", f"Air by the outline route: {min(airs):.0f}–{max(airs):.0f} cm³. The lowest note whose column holds that range is the "
           "pitch the size fits. A 12-hole in A has F♯4 as its lowest note.", ""]

    # Alto C: which length makes the two routes agree at A4
    md += ["## 3. Songbird Alto C (A4–F6): the body length its holes fit", "",
           "No mass is known, so the fired clay is surface × wall thickness. Thickness / width 0.75 and 0.80. "
           "The holes scale with the body. A length is consistent when the two volumes agree.", "",
           "| Body length mm | V0 from the holes at A4, cm³ (rim − 1 mm … rim; walls 6 and 5 mm) | Air by the outline route, cm³ (wall 6 mm, T/W 0.75 … wall 5 mm, T/W 0.80) |",
           "|---|---|---|"]
    table = []
    for Lc in (140.0, 152.4, 160.0, 165.0, 170.0, 175.0, 181.0, 190.0):
        vs = []
        for off in (-1.0, 0.0):
            for wall in (6.0, 5.0):
                d = [f * Lc + off for f in frac] + [t * Lc + off for t in thumbs]
                vs.append(v0_from_holes(d, [wall] * 12)[0])
        w, s = outline(sb, Lc / L0)
        ga = [outer_volume_cm3(w, s, tw) - shell_cm3(w, s, tw, wall) for tw, wall in ((0.75, 6.0), (0.75, 5.0), (0.80, 6.0), (0.80, 5.0))]
        table.append((Lc, min(vs), max(vs), min(ga), max(ga)))
        md.append(f"| {Lc:.1f} | {min(vs):.0f}–{max(vs):.0f} | {min(ga):.0f}–{max(ga):.0f} |")
    ok_len = [t[0] for t in table if t[1] <= t[4] and t[3] <= t[2]]
    md += ["", (f"The two ranges overlap from {min(ok_len):.0f} to {max(ok_len):.0f} mm." if ok_len else "The two ranges do not overlap in this table."),
           "Below that the body holds less air than its holes need for A4; above it, more."]
    text = "\n".join(md) + "\n"
    (HERE / "ceramic_volume_check.md").write_text(text, encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
