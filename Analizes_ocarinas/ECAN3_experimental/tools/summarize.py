"""Cross-model comparison table from output/<model>/results.json.

    python Analizes_ocarinas/ECAN3_experimental/tools/summarize.py

Writes output/summary.md.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
USER_BLENDER_10H_MM3 = 66784.2452       # user's Blender 3D-Print-Toolbox volume of the V0N3 inner chamber


def main():
    try:
        import sys
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    res = {}
    for p in sorted((ROOT / "output").glob("*/results.json")):
        res[p.parent.name] = json.loads(p.read_text(encoding="utf-8"))
    names = list(res)
    L = ["# ECAN3 models: cross-model summary", "", "Generated by `tools/summarize.py` from `output/<model>/results.json`.", "",
         "| Quantity | " + " | ".join(names) + " |", "| --- |" + " --- |" * len(names)]

    def row(label, fn, fmt="{:,.0f}"):
        vals = []
        for n in names:
            try:
                v = fn(res[n])
                vals.append(fmt.format(v) if v is not None else "—")
            except Exception:
                vals.append("—")
        L.append(f"| {label} | " + " | ".join(vals) + " |")

    row("Range (notes)", lambda r: f"{r['scale'][0]['note']}–{r['scale'][-1]['note']}", "{}")
    row("Outer extents x·y·z, mm", lambda r: "×".join(f"{e:.0f}" for e in r["mesh"]["mesh_extents_mm"]), "{}")
    row("Plastic (mesh) volume, mm³", lambda r: r["volumes"]["mesh_solid_mm3"])
    row("Air V0, capped at outer rims, mm³", lambda r: r["volumes"]["V0_air_capped_at_outer_rims_mm3"])
    row("Internal walls (displacement), mm³", lambda r: r["volumes"]["internal_walls_mm3"])
    row("Gross chamber (air + walls), mm³", lambda r: r["volumes"]["gross_chamber_air_plus_walls_mm3"])
    row("Wall displacement, % of gross", lambda r: r["volumes"]["wall_displacement_pct_of_gross"], "{:.1f}")
    row("Uniform pitch effect of displacement, cents", lambda r: r["scale"][0]["walls_effect_kernel_cents"], "{:+.1f}")
    row("Shell thickness at holes (median t), mm",
        lambda r: sorted(h["t"] for h in r["holes"].values())[len(r["holes"]) // 2], "{:.2f}")
    row("Hole d_eq range, mm", lambda r: f"{min(h['d_eq'] for h in r['holes'].values()):.2f}–{max(h['d_eq'] for h in r['holes'].values()):.2f}", "{}")
    row("Window outer aperture, mm²", lambda r: r["window"]["A_outer_mm2"], "{:.1f}")
    row("Window G fitted (kernel), mm", lambda r: r["window"]["G_fit_kernel"], "{:.2f}")
    row("Window area / V0^(2/3)", lambda r: r["window"]["A_outer_mm2"] / r["volumes"]["V0_air_capped_at_outer_rims_mm3"] ** (2 / 3), "{:.4f}")
    row("Sub-volumes (gaps < 5 mm / < 8 mm)", lambda r: f"{len(r['subvolumes']['volumes_mm3'])} / {len(r['subvolumes_8mm']['volumes_mm3'])}", "{}")
    row("Best-fit k: kernel / network", lambda r: f"{r['k_fit']['kernel']:.2f} / {r['k_fit']['network']:.2f}", "{}")
    row("RMS cents at k 0.8: kernel / network", lambda r: f"{r['rms_cents']['kernel']:.0f} / {r['rms_cents']['network']:.0f}", "{}")
    row("RMS cents at fitted k: kernel / network", lambda r: f"{r['rms_cents']['kernel_kfit']:.0f} / {r['rms_cents']['network_kfit']:.0f}", "{}")
    row("Network walls effect, lowest note, cents", lambda r: r["scale"][0]["walls_effect_network_cents"], "{:+.0f}")
    row("Network walls effect, top note, cents", lambda r: r["scale"][-1]["walls_effect_network_cents"], "{:+.0f}")
    row("V_eff/V: lowest / top note", lambda r: f"{r['scale'][0]['V_eff_over_V0']:.2f} / {r['scale'][-1]['V_eff_over_V0']:.2f}", "{}")
    row("First cavity mode / top note", lambda r: r["network"]["first_cavity_mode_over_top_note"], "{:.2f}")
    if "v0n3" in res:
        v = res["v0n3"]["volumes"]
        L += ["", f"User's Blender reference for the 10-hole inner chamber: {USER_BLENDER_10H_MM3:,.1f} mm³. "
              f"This analysis: air capped at the outer rims {v['V0_air_capped_at_outer_rims_mm3']:,.0f} mm³ "
              f"({100*(v['V0_air_capped_at_outer_rims_mm3']/USER_BLENDER_10H_MM3-1):+.1f} %), "
              f"air without closed chimneys {v['V0_air_capped_at_outer_rims_mm3']-v['closed_chimneys_in_V0_mm3']:,.0f} mm³ "
              f"({100*((v['V0_air_capped_at_outer_rims_mm3']-v['closed_chimneys_in_V0_mm3'])/USER_BLENDER_10H_MM3-1):+.1f} %), "
              f"gross (air + walls) {v['gross_chamber_air_plus_walls_mm3']:,.0f} mm³."]
    (ROOT / "output" / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
