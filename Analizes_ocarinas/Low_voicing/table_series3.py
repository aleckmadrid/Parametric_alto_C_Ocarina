"""Tables of series 3 from series3_trials.json and walls_desk_model.json.

    python Analizes_ocarinas/Low_voicing/table_series3.py > Analizes_ocarinas/Low_voicing/tables_s3.md
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
T = json.loads((HERE / "series3_trials.json").read_text(encoding="utf-8"))
DESK = json.loads((HERE / "walls_desk_model.json").read_text(encoding="utf-8")) if (HERE / "walls_desk_model.json").exists() else {}
BASE = ("s3-c42", "s3-c38", "s3-c34", "s3-c32", "s3-fw", "s3-fwr")
WALLS = ("s3-fwr", "s3-w25", "s3-w38", "s3-w50", "s3-wL", "s3-wR", "s3-wf", "s3-wt16", "s3-wt40", "s3-fwr30", "s3-w30")


def status(r):
    return "passes" if not r["unexpected"] else "FAILS: " + ", ".join(r["unexpected"])


def main():
    out = ["# Series 3: tables (generated by table_series3.py)", ""]
    out += ["## Step 0: the foot of the neck at port 10°, by the corrected check", "",
            "| Body | Trial | Foot of the neck (wide × deep) | Most plastic of the neck beside a thumb hole rim (L / R) | "
            "The old box distance (L / R) | Thumb hole edge to the window (L / R) | First cavity mode ÷ F6 | Plastic | Checks |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for pid in ("P4", "P1"):
        for t in BASE:
            r = T.get(f"{pid}:{t}")
            if not r:
                continue
            L, R, n = r["thumbs"]["L_thumb"], r["thumbs"]["R_thumb"], r["neck"]
            out.append(f"| {pid} | `{t}` | {n['base_width_mm']:.1f} × {n['base_depth_mm']:.1f} mm | "
                       f"{L['plastic_on_skin_at_rim_mm']:.2f} / {R['plastic_on_skin_at_rim_mm']:.2f} mm | "
                       f"{L['to_block_mm']:+.1f} / {R['to_block_mm']:+.1f} mm | {L['to_window_mm']:.1f} / {R['to_window_mm']:.1f} mm | "
                       f"{r['cavity_mode']['ratio']:.3f} | {r['plastic_cm3']:.1f} cm³ | {status(r)} |")
    out += ["", "## The room for an inner wall (control `s3-fwr`; x along the body from the lip)", "",
            "| Body | Window | The pocket's flat part | Where the pocket still adds air to the section | Left thumb hole | Right thumb hole | "
            "Room left / right (hole rim to the end of the pocket's skirt) |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for pid in ("P4", "P1"):
        m = T[f"{pid}:s3-fwr"]["room"]
        xs = [float(k) for k, s in m["sections"].items() if s["pocket_adds_mm2"] > 0.3]
        hl, hr = m["holes"]["L_thumb"], m["holes"]["R_thumb"]
        out.append(f"| {pid} | {m['window_x_mm'][0]:+.1f} to {m['window_x_mm'][1]:+.1f} | {m['pocket_flat_x_mm'][0]:+.1f} to {m['pocket_flat_x_mm'][1]:+.1f} | "
                   f"{min(xs):+.0f} to {max(xs):+.0f} | {hl['x_range_mm'][0]:+.1f} to {hl['x_range_mm'][1]:+.1f} (⌀ {hl['d_mm']:.1f}) | "
                   f"{hr['x_range_mm'][0]:+.1f} to {hr['x_range_mm'][1]:+.1f} (⌀ {hr['d_mm']:.1f}) | "
                   f"{min(xs) - hl['x_range_mm'][1]:.1f} / {hr['x_range_mm'][0] - max(xs):.1f} mm (sections every 1 mm) |")
    out += ["", "## Stage W, first pass: the inner walls", "",
            "| Body | Trial | Walls (x, thickness, fillet toward −x / +x) | Top edge above the thumb-face wall | Section blocked | "
            "Wall to its thumb hole rim | Wall to the window | Wall in the pocket's air | Air taken; chamber grown | Capped air as the check measures it (built: 80.01) | Plastic | "
            "First cavity mode ÷ F6 (1.5 mm grid) | Checks |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for pid in ("P4", "P1"):
        for t in WALLS:
            r = T.get(f"{pid}:{t}")
            if not r:
                continue
            w = (r.get("inner_walls") or {}).get("walls") or {}
            j = lambda f: " / ".join(f(x) for x in w.values()) if w else "–"      # noqa: E731
            out.append(f"| {pid} | `{t}` | " + ("; ".join(f"{n} {x['x_mm']:+.1f}, {x['thickness_mm']:g}, {x['fillet_mm'][0]:.1f} / {x['fillet_mm'][1]:.1f}" for n, x in w.items()) or "none")
                       + f" | {j(lambda x: format(x['top_above_thumb_wall_mm'], '.1f'))} mm"
                       + f" | {j(lambda x: str(round(100 * x['blocked_share'])) + ' %')}"
                       + f" | {j(lambda x: format(min(h['rim_to_wall_mm'] for h in x['thumb_holes'].values()), '.2f'))} mm"
                       + f" | {j(lambda x: format(x['window_to_wall_mm'], '.1f'))} mm"
                       + f" | {j(lambda x: format(x['in_pocket_air_mm3'], '.1f'))} mm³"
                       + f" | {sum(x['air_taken_cm3'] for x in w.values()):.2f}; {(r.get('inner_walls') or {}).get('chamber_grown_cm3', 0.0):.2f} cm³"
                       + f" | {r['capped_air_cm3']:.2f} cm³ | {r['plastic_cm3']:.1f} cm³ | {r['cavity_mode']['ratio']:.3f} | {status(r)} |")
    if DESK:
        out += ["", "## Desk model on a 1.0 mm grid (walls_desk_model.py)", "",
                "| Body | Trial | Closed: first cavity mode ÷ F6 | Smooth twin | Left thumb's effect left | Right thumb's | Both | Both thumbs open: next mode ÷ F6 |",
                "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        for pid in ("P4", "P1"):
            for t in WALLS:
                d = DESK.get(f"{pid}:{t}@1")
                if not d:
                    continue
                pc = lambda k: f"{100 * d[k]:.0f} %" if k in d else "–"      # noqa: E731
                tw = f"{d['closed_ratio_twin']:.2f}" if "closed_ratio_twin" in d else "–"
                out.append(f"| {pid} | `{t}` | {d['closed_ratio']:.2f} | {tw} | {pc('conductance_left_L')} | {pc('conductance_left_R')} | "
                           f"{pc('conductance_left_LR')} | {d['next_LR_open_ratio']:.2f} |")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
